-- Personal journal paper crawler: initial schema.
-- All access goes through the server with the service role key. RLS is on everywhere with
-- no policies, so the anon/authenticated keys can read or write nothing.

create extension if not exists pgcrypto;

create type paper_type as enum ('article', 'review', 'preprint', 'conference');
create type paper_status as enum ('active', 'filtered');
create type paper_label as enum ('relevant', 'close', 'not_related');
create type source_name as enum ('openalex', 'crossref', 'europepmc');

create table topic_groups (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  -- array of concept blocks; each block is an array of synonym strings (OR), blocks are AND'ed
  blocks jsonb not null default '[]'::jsonb check (jsonb_typeof(blocks) = 'array'),
  exclude_terms text[] not null default '{}',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table runs (
  id bigint generated always as identity primary key,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  status text not null default 'running' check (status in ('running', 'done', 'partial', 'error', 'abandoned')),
  params jsonb not null default '{}'::jsonb,  -- cap, look-back, per-pair windows
  summary jsonb not null default '{}'::jsonb
);

create table papers (
  -- "by default" so the crawler can upsert existing rows by id
  id bigint generated by default as identity primary key,
  doi text unique,                       -- lowercased, no https://doi.org/ prefix
  title_hash text not null,              -- sha1(normalised title | year): fallback dedupe key
  title text not null,
  abstract text,
  authors jsonb not null default '[]'::jsonb,
  journal text,
  issn_l text,
  issns text[] not null default '{}',
  pub_date date,
  year int,
  type paper_type not null,
  fields jsonb,                          -- [{id, name, level}] from OpenAlex; null = unknown
  unclassified boolean not null default false,
  sources source_name[] not null default '{}',
  status paper_status not null default 'active',
  label paper_label,
  labeled_at timestamptz,
  score double precision,
  first_seen_run_id bigint references runs(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  fts tsvector
);

create index papers_title_hash_idx on papers (title_hash);
create index papers_inbox_idx on papers (first_seen_run_id desc, score desc nulls last) where label is null;
create index papers_label_idx on papers (label, labeled_at desc);
create index papers_fts_idx on papers using gin (fts);
create index papers_sources_idx on papers using gin (sources);

-- Full-text vector over title (A), abstract (B) and authors (C, no stemming).
create or replace function papers_fts_update() returns trigger
language plpgsql as $$
begin
  new.fts :=
    setweight(to_tsvector('english', coalesce(new.title, '')), 'A') ||
    setweight(to_tsvector('english', coalesce(new.abstract, '')), 'B') ||
    setweight(to_tsvector('simple', coalesce(
      (select string_agg(value, ' ') from jsonb_array_elements_text(coalesce(new.authors, '[]'::jsonb))), '')), 'C');
  new.updated_at := now();
  return new;
end $$;

create trigger papers_fts_trg before insert or update of title, abstract, authors on papers
for each row execute function papers_fts_update();

create table paper_topics (
  paper_id bigint not null references papers(id) on delete cascade,
  topic_group_id uuid not null references topic_groups(id) on delete cascade,
  primary key (paper_id, topic_group_id)
);
create index paper_topics_topic_idx on paper_topics (topic_group_id);

create table run_steps (
  id bigint generated always as identity primary key,
  run_id bigint not null references runs(id) on delete cascade,
  topic_group_id uuid references topic_groups(id) on delete set null,
  source source_name not null,
  page int not null,
  fetched int not null default 0,   -- records returned by the source
  nomatch int not null default 0,   -- failed the local boolean rule or unsupported type (not stored)
  new int not null default 0,       -- papers not seen before
  dupes int not null default 0,     -- already in the database (merged)
  filtered int not null default 0,  -- failed the venue rule (stored with status 'filtered')
  cap_hit boolean not null default false,
  error text,
  created_at timestamptz not null default now()
);
create index run_steps_run_idx on run_steps (run_id);

create table source_cursors (
  topic_group_id uuid not null references topic_groups(id) on delete cascade,
  source source_name not null,
  last_until timestamptz not null,
  primary key (topic_group_id, source)
);

create table journal_whitelist (
  issn_l text primary key,
  name text not null,
  issns text[] not null default '{}',  -- all ISSNs of the journal, so Crossref/EPMC ISSNs match too
  openalex_id text,
  created_at timestamptz not null default now()
);

create table allowed_fields (
  openalex_id text primary key,       -- 'fields/15' or 'subfields/1305'
  name text not null,
  level text not null check (level in ('field', 'subfield'))
);

-- Bulk score update: [{ "id": 1, "score": 0.42 }, ...]
create or replace function set_scores(scores jsonb) returns void
language sql as $$
  update papers p set score = s.score
  from jsonb_to_recordset(scores) as s(id bigint, score double precision)
  where p.id = s.id and p.score is distinct from s.score;
$$;

-- Lock everything down: RLS on, no policies, and no grants to the public API roles.
alter table topic_groups enable row level security;
alter table runs enable row level security;
alter table papers enable row level security;
alter table paper_topics enable row level security;
alter table run_steps enable row level security;
alter table source_cursors enable row level security;
alter table journal_whitelist enable row level security;
alter table allowed_fields enable row level security;

do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    execute 'revoke all on all tables in schema public from anon';
    execute 'revoke execute on function set_scores(jsonb) from anon';
  end if;
  if exists (select 1 from pg_roles where rolname = 'authenticated') then
    execute 'revoke all on all tables in schema public from authenticated';
    execute 'revoke execute on function set_scores(jsonb) from authenticated';
  end if;
end $$;
revoke execute on function set_scores(jsonb) from public;
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'service_role') then
    execute 'grant all on all tables in schema public to service_role';
    execute 'grant execute on function set_scores(jsonb) to service_role';
  end if;
end $$;
